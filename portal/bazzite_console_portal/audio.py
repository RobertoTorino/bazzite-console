"""The portal's sounds (sounds/): the intro's when the portal opens (made by tools/make_portal_sounds.py), the
welcome when the intro has ended (welcome.wav, owner 20-11-2026: made by the owner in Nexus Remix Studio, its voice
generated by Nexus TTS, the suite's own, GPL-3.0-or-later as the rest; a suite without the file plays none), and a short one on every controller action
(blob.wav, owner 05-11-2026: made by the owner in Audacity, the suite's own, GPL-3.0-or-later as the rest; replace it
with any short WAV of the same name). Without an audio output, or without Qt's multimedia, the portal stays silent
and says nothing."""

from __future__ import annotations

from pathlib import Path

from PyQt6.QtCore import QUrl

SOUNDS = Path(__file__).resolve().parent / "sounds"
INTRO = "bigpicture"
WELCOME = "welcome"             # when the intro has ended; not after a skip
ACTION = "blob"                 # a controller action: a move, a button
VOLUME = 0.7
VOLUMES = {WELCOME: 1.0}        # a sound with a volume of its own (owner, 20-11-2026: the welcome louder)
NO_OUTPUT = "No audio output was found, so the portal stays silent."


class Sounds:
    """Plays the portal's sound; *enabled* is the user's choice (the Sound pill), available() whether the board has
    an audio output to play on."""

    def __init__(self, folder: Path = SOUNDS):
        self.folder = folder
        self.enabled = True
        self._effects: dict[str, object] = {}

    def available(self) -> bool:
        try:
            from PyQt6.QtMultimedia import QMediaDevices
            return bool(QMediaDevices.audioOutputs())
        except Exception:  # noqa: BLE001  (any failure of the multimedia stack: no sound)
            return False

    def _effect(self, name: str):
        if name not in self._effects:
            path = self.folder / f"{name}.wav"
            if not path.is_file():
                return None
            from PyQt6.QtMultimedia import QSoundEffect
            effect = QSoundEffect()
            effect.setSource(QUrl.fromLocalFile(str(path)))
            effect.setVolume(VOLUMES.get(name, VOLUME))
            self._effects[name] = effect
        return self._effects[name]

    def prepare(self, name: str) -> None:
        """Read *name* now, so a later play() starts without a delay."""
        if not self.enabled or not self.available():
            return
        try:
            self._effect(name)
        except Exception:  # noqa: BLE001  (as play())
            pass

    def play(self, name: str) -> bool:
        """Play *name* once, from its start; False when it did not (sound off, no output, no file)."""
        if not self.enabled or not self.available():
            return False
        try:
            effect = self._effect(name)
            if effect is None:
                return False
            effect.stop()
            effect.play()
        except Exception:  # noqa: BLE001  (a sound that cannot play never gets in the way)
            return False
        return True

    def stop(self) -> None:
        for effect in self._effects.values():
            effect.stop()
